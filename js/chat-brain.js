  function findUrl(raw) {
    var m = String(raw).match(/\b((?:https?:\/\/)?(?:www\.)?[a-z0-9-]+(?:\.[a-z0-9-]+)*\.(?:co\.ke|or\.ke|ac\.ke|go\.ke|ke|com|org|net|africa|co|io|biz|info|shop|store|online|site|tech|app))(\/[^\s]*)?\b/i);
    if (!m) { return null; }
    if (/@/.test(raw.slice(Math.max(0, m.index - 1), m.index + 1))) { return null; }   // part of an e-mail
    return m[1] + (m[2] || "");
  }

