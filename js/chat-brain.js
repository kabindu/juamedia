  function findName(raw) {
    var m = String(raw).match(/\b(?:my name is|my names|i am|i'm|im|this is|naitwa|jina langu ni)\s+([a-z]{2,15})\b/i);
    if (!m) { return null; }
    var w = m[1].toLowerCase();
    var bad = ["looking", "interested", "from", "here", "just", "not", "in", "at", "the", "a", "an", "good", "fine", "okay", "ok",
      "running", "planning", "trying", "wondering", "new", "starting", "selling", "based", "a", "very", "so", "also", "still", "glad", "happy", "sure"];
    // "I am X" only counts when X is capitalised; "my name is x" always counts
    if (!/my name|naitwa|jina langu|this is/i.test(m[0]) && !/^[A-Z]/.test(m[1])) { return null; }
    return bad.indexOf(w) === -1 ? cap(w) : null;
  }

